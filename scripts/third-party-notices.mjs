#!/usr/bin/env node
// Generate THIRD-PARTY-NOTICES.md for the shipped skill bundles.
//
// rolldown strips license headers when it inlines node_modules; MIT/ISC/BSD
// all require the notice to travel with redistributed source. This walks the
// `//#region node_modules/<pkg>/…` markers rolldown leaves in each bundle,
// resolves every package's package.json and LICENSE file, and writes one
// aggregated notices file. Deterministic: sorted by package name, so the
// output is stable across rebuilds and check-bundle can diff it.
//
// usage: node scripts/third-party-notices.mjs <out-file> <bundle>...

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const [outFile, ...bundles] = process.argv.slice(2);
if (!outFile || bundles.length === 0) {
  console.error('usage: third-party-notices.mjs <out-file> <bundle>...');
  process.exit(2);
}

// Marker → package name: "node_modules/@scope/name/dist/x.js" → "@scope/name".
function packageFromRegion(path) {
  const parts = path.split('/');
  const i = parts.lastIndexOf('node_modules');
  if (i === -1) return null;
  const first = parts[i + 1];
  return first?.startsWith('@') ? `${first}/${parts[i + 2]}` : first ?? null;
}

const packages = new Set();
for (const bundle of bundles) {
  const text = readFileSync(bundle, 'utf8');
  for (const m of text.matchAll(/^\/\/#region (node_modules\/\S+)/gm)) {
    const name = packageFromRegion(m[1]);
    if (name) packages.add(name);
  }
}

function findLicenseFile(dir) {
  const candidates = readdirSync(dir).filter(f => /^(LICEN[CS]E|COPYING)(\.|$)/i.test(f));
  return candidates.length ? join(dir, candidates.sort()[0]) : null;
}

const missing = [];
const sections = [];
for (const name of [...packages].sort()) {
  const dir = join(repoRoot, 'node_modules', name);
  const pkgPath = join(dir, 'package.json');
  if (!existsSync(pkgPath)) { missing.push(`${name}: package.json not found`); continue; }
  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
  const license = typeof pkg.license === 'string' ? pkg.license : (pkg.license?.type ?? 'UNKNOWN');
  const licensePath = findLicenseFile(dir);
  if (!licensePath) missing.push(`${name}@${pkg.version}: no LICENSE file (declared ${license})`);
  const author = typeof pkg.author === 'string' ? pkg.author : pkg.author?.name;
  const body = licensePath ? readFileSync(licensePath, 'utf8').trim() : `(no license file shipped; declared ${license})`;
  sections.push(
    `## ${name}@${pkg.version}\n\n` +
    `- License: ${license}\n` +
    (author ? `- Author: ${author}\n` : '') +
    (pkg.homepage || pkg.repository?.url ? `- Source: ${pkg.homepage ?? pkg.repository.url}\n` : '') +
    `\n\`\`\`\n${body}\n\`\`\`\n`
  );
}

const header =
  `# Third-Party Notices\n\n` +
  `The shipped bundles (${bundles.map(b => `\`${b.replace(repoRoot + '/', '')}\``).join(', ')}) ` +
  `inline source from the ${sections.length} packages below. Each is redistributed under its ` +
  `own license, reproduced here as required. Generated by \`scripts/third-party-notices.mjs\` ` +
  `from \`scripts/build-viewer.sh\`; do not edit by hand.\n\n`;

writeFileSync(outFile, header + sections.join('\n'));
console.log(`wrote ${outFile}: ${sections.length} packages`);
for (const m of missing) console.error(`warn: ${m}`);
